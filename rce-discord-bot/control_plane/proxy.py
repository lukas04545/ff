"""Reverse proxy config (Caddy): <slug>.<BASE_DOMAIN> -> the tenant's own web port on 127.0.0.1.

One site block per server; suspended/over-limit/stopped servers point at the control plane's "paused" page, so a
lapsed customer's website shows a friendly notice instead of an error – and comes back by itself on reactivation.
The main Caddyfile just has `import /var/lib/rce-saas/Caddyfile.tenants` plus the portal site. TLS: Caddy gets the
certificates (or put Cloudflare in front with a wildcard record – recommended for DDoS protection).

X-Forwarded-For is always set: the bot treats requests from 127.0.0.1 WITHOUT it as "this PC" (trusted), so every
proxied request must carry it.
"""
from __future__ import annotations

import asyncio
import os
import shlex

from control_plane.db import DB
from control_plane.settings import Settings

RUNNING = ("active",)


def render(db: DB, settings: Settings) -> str:
    rows = db.q("SELECT id, slug, status, web_port FROM servers WHERE status != 'deleted' ORDER BY slug")
    blocks = ["# Generated by the control plane – don't edit, changes are overwritten."]
    for r in rows:
        host = f"{r['slug']}.{settings.base_domain}"
        if r["status"] in RUNNING:
            target = f"127.0.0.1:{r['web_port']}"
            extra = ""
        else:
            target = f"{settings.portal_host}:{settings.portal_port}"
            extra = f"\n        rewrite * /paused/{r['slug']}"
        blocks.append(f"""{host} {{
    reverse_proxy {target} {{
        header_up X-Forwarded-For {{remote_host}}
        header_up X-Forwarded-Proto {{scheme}}
    }}{extra}
    request_body {{
        max_size 2MB
    }}
}}""")
    return "\n\n".join(blocks) + "\n"


async def apply(db: DB, settings: Settings) -> bool:
    """Writes the tenants file if it changed and reloads Caddy. Returns True if something changed."""
    text = render(db, settings)
    path = settings.caddy_file
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except FileNotFoundError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    if settings.caddy_reload:
        proc = await asyncio.create_subprocess_exec(*shlex.split(settings.caddy_reload),
                                                    stdout=asyncio.subprocess.DEVNULL,
                                                    stderr=asyncio.subprocess.DEVNULL)
        await proc.wait()
    return True
